const assert = require('node:assert/strict');
const grid = require('../notion_static/notion_grid_selection.js');
const rows = ['page-a','page-b','page-c'], columns = ['title','count','done'];
const range = grid.rectangle(rows, columns, {row:'page-c',column:'done'}, {row:'page-a',column:'count'});
assert.equal(range.length,6);
assert.deepEqual(range[0],{row:'page-a',column:'count'});
assert.deepEqual(grid.rectangle(rows.slice(1),columns,{row:'page-a',column:'count'},{row:'page-c',column:'count'}),[]);
const data=[['한글\n다음 줄','a\tb','"quoted"'],['','','끝']];
assert.deepEqual(grid.parseTsv(grid.toTsv(data)),data);
assert.deepEqual(grid.parseTsv('a\tb\r\nc\td\r\n'),[['a','b'],['c','d']]);
assert.throws(()=>grid.parseTsv('a\tb\nc'));
assert.throws(()=>grid.parseTsv('"a'));
assert.equal(grid.typedValue('number','12.5'),12.5);
assert.equal(grid.typedValue('number',''),'');
assert.throws(()=>grid.typedValue('number','12x'));
assert.throws(()=>grid.typedValue('number','Infinity'));
assert.equal(grid.typedValue('checkbox','true'),true);
assert.equal(grid.typedValue('checkbox',''),false);
assert.throws(()=>grid.typedValue('checkbox','maybe'));
assert.throws(()=>grid.typedValue('date','2026-02-30'));
assert.equal(grid.typedValue('date','2028-02-29'),'2028-02-29');
assert.throws(()=>grid.typedValue('formula','1'));
assert.throws(()=>grid.typedValue('person','missing',['allowed']));
assert.equal(grid.typedValue('person','allowed',['allowed']),'allowed');
assert.throws(()=>grid.typedValue('url','javascript:alert(1)'));
assert.equal(grid.typedValue('text','  keep spaces  '),'  keep spaces  ');
console.log('Notion grid range, TSV and type validation passed');
const core=require('../notion_static/notion_editor_core');
let history=core.pushHistory(null,{blocks:[{props:{score:10,text:'a'}}]});
history=core.pushHistory(history,{blocks:[{props:{score:20,text:'a'}}]});
history=core.pushHistory(history,{blocks:[{props:{text:'a',score:20}}]});
assert.equal(history.entries.length,2,'save key ordering does not add a history entry');
const undone=core.historyStep(history,-1);
history=core.pushHistory(undone.history,{blocks:[{props:{text:'a',score:10}}]});
assert.equal(history.entries.length,2,'an unchanged snapshot preserves the redo branch');
assert.equal(core.historyStep(history,1).snapshot.blocks[0].props.score,20);
console.log('Auto-save history equivalence and redo preservation passed');
