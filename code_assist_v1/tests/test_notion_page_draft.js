"use strict";
const assert = require("node:assert/strict");
const draft = require("../notion_static/notion_page_draft.js");
const empty = {page:{title:""},blocks:[{type:"paragraph",content:"",props:{}}]};
(async () => {
  const session = draft.create({parentId:"parent",workspaceId:"one"},"intent-1");
  let calls=0, finish;
  const requests=[];
  const send = request => {calls++;requests.push(request);return new Promise(resolve=>{finish=resolve;});};
  assert.equal(await session.commit(empty,send),null);
  assert.equal(calls,0,"opening/closing empty drafts does not create pages");
  const data=structuredClone(empty);data.page.title="초안";
  const first=session.commit(data,send), second=session.commit(data,send);
  assert.equal(first,second,"double submit shares one in-flight creation");
  await Promise.resolve(); data.page.title="추가 입력";
  assert.equal(requests[0].data.page.title,"초안");
  finish({page:{id:"created"}});await first;
  assert.equal((await session.commit(data,send)).page.id,"created");assert.equal(calls,1);
  const retry=draft.create({parentId:"parent"},"intent-2");let attempt=0;const sent=[];
  const unreliable=async request=>{sent.push(request);if(!attempt++)throw new Error("response lost");return {page:{id:"same-page"}};};
  await assert.rejects(retry.commit(data,unreliable));assert.equal(retry.phase,"failed");
  data.page.title="오류 뒤에도 입력";
  await retry.commit(data,unreliable);
  assert.deepEqual(sent[0],sent[1],"response-loss retry keeps the exact original input and operation ID");
  assert.equal(retry.phase,"created");
  assert.equal(draft.hasContent({...empty,page:{title:" \n "}}),false);
  assert.equal(draft.hasContent({...empty,page:{title:"",icon:"🌿"}}),true);
  assert.equal(draft.hasContent({...empty,appearancePending:false}),false,"cancelled image selection does not create an empty page");
  assert.equal(draft.hasContent({...empty,appearancePending:true}),true,"applied image intent can create its owning page before upload");
  assert.equal(draft.hasContent({...empty,blocks:[{type:"paragraph",content:"본문"}]}),true);
  console.log("UI-DRAFT-001: empty cancel, duplicate submit, immutable retry and meaningful content passed");
})().catch(error=>{console.error(error);process.exitCode=1;});
