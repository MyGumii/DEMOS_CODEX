"""Reviewed physical-schema fingerprints for numbered SQLite migrations.

Ordinary connections only hash their live ``sqlite_schema`` and compare it to
the immutable value embedded in ``Migration``. This module's build helper is
the explicit offline path for generating cumulative values; it never runs from
``ConnectionFactory.open()``.
"""

from __future__ import annotations

import hashlib
import json
import sqlite3
from typing import Protocol

from ..errors import KnowledgeCoreMigrationError, KnowledgeCoreRuntimeMismatchError
from ..runtime import APPROVED_SQLITE_SOURCE_ID, APPROVED_SQLITE_VERSION
from .model import _normalized_sql


class _QueryCursor(Protocol):
    def fetchall(self) -> list[object]: ...


class _QueryConnection(Protocol):
    def execute(self, sql: str, parameters: object = ()) -> _QueryCursor: ...


EMPTY_SCHEMA_SHA256 = hashlib.sha256(b"[]").hexdigest()


def schema_sha256(connection: _QueryConnection) -> str:
    cursor = connection.execute(
        "SELECT type,name,tbl_name,coalesce(sql,'') FROM sqlite_schema "
        "WHERE name NOT LIKE 'sqlite_%' ORDER BY type,name,tbl_name,sql"
    )
    normalized: list[tuple[str, str, str, str]] = []
    for row in cursor.fetchall():
        values = tuple(row)  # type: ignore[arg-type]
        if len(values) != 4 or any(not isinstance(value, str) for value in values):
            raise KnowledgeCoreMigrationError(
                "SQLite returned an invalid physical schema record."
            )
        normalized.append(values)  # type: ignore[arg-type]
    encoded = json.dumps(
        normalized,
        ensure_ascii=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def build_cumulative_schema_sha256(
    statement_groups: tuple[tuple[str, ...], ...],
    *,
    require_approved_runtime: bool = True,
    requires_foreign_keys_off_versions: frozenset[int] = frozenset(),
) -> tuple[str, ...]:
    """Execute normalized statements in memory and return each version manifest."""

    groups = tuple(
        tuple(_normalized_sql(sql) for sql in group) for group in statement_groups
    )
    if not groups or any(not group for group in groups):
        raise KnowledgeCoreMigrationError(
            "Schema fingerprint generation requires non-empty migration groups."
        )
    if (
        not isinstance(requires_foreign_keys_off_versions, frozenset)
        or any(
            isinstance(version, bool)
            or not isinstance(version, int)
            or version < 1
            or version > len(groups)
            for version in requires_foreign_keys_off_versions
        )
    ):
        raise KnowledgeCoreMigrationError(
            "Foreign-key-off schema versions must be a bounded frozenset."
        )
    connection = sqlite3.connect(":memory:", isolation_level=None)
    try:
        version, source_id = connection.execute(
            "SELECT sqlite_version(), sqlite_source_id()"
        ).fetchone()
        if require_approved_runtime and (
            version != APPROVED_SQLITE_VERSION
            or source_id != APPROVED_SQLITE_SOURCE_ID
        ):
            raise KnowledgeCoreRuntimeMismatchError(
                "Schema fingerprints must be generated by the approved SQLite build."
            )
        connection.execute(
            "PRAGMA foreign_keys = OFF"
            if requires_foreign_keys_off_versions
            else "PRAGMA foreign_keys = ON"
        )
        if requires_foreign_keys_off_versions:
            connection.execute("PRAGMA legacy_alter_table = ON")
        connection.execute("PRAGMA trusted_schema = OFF")
        connection.execute("PRAGMA recursive_triggers = ON")
        connection.execute("BEGIN EXCLUSIVE")
        fingerprints: list[str] = []
        for group in groups:
            for statement in group:
                connection.execute(statement)
            fingerprints.append(schema_sha256(connection))
        if connection.execute("PRAGMA foreign_key_check").fetchone() is not None:
            raise KnowledgeCoreMigrationError(
                "Schema fingerprint generation found a foreign-key violation."
            )
        connection.rollback()
        return tuple(fingerprints)
    except (KnowledgeCoreMigrationError, KnowledgeCoreRuntimeMismatchError):
        raise
    except sqlite3.Error as exc:
        raise KnowledgeCoreMigrationError(
            "Schema fingerprint generation failed."
        ) from exc
    finally:
        connection.close()


__all__ = [
    "EMPTY_SCHEMA_SHA256",
    "build_cumulative_schema_sha256",
    "schema_sha256",
]
